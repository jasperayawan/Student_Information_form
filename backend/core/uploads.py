"""Student photo files: validation and storage.

Photos are stored next to the database file (database/uploads/students/)
under random names, and are only served through an authenticated endpoint.
"""
import uuid
from pathlib import Path

from fastapi import HTTPException

from database import DATABASE

PHOTO_DIR = DATABASE.parent / "uploads" / "students"
MAX_PHOTO_BYTES = 2 * 1024 * 1024
MEDIA_TYPES = {".jpg": "image/jpeg", ".png": "image/png", ".webp": "image/webp"}


def detect_image_type(data: bytes) -> str | None:
    """Identify the format from the file's own bytes, never trusting the
    file name or the browser-supplied content type."""
    if data.startswith(b"\xff\xd8\xff"):
        return ".jpg"
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return ".png"
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return ".webp"
    return None


def validate_photo(data: bytes) -> str:
    if not data:
        raise HTTPException(status_code=422, detail="The photo file is empty.")
    if len(data) > MAX_PHOTO_BYTES:
        raise HTTPException(status_code=413, detail="The photo is larger than 2 MB.")
    extension = detect_image_type(data)
    if extension is None:
        raise HTTPException(status_code=422, detail="Please upload a JPG, PNG or WebP image.")
    return extension


def save_photo(data: bytes, extension: str) -> str:
    PHOTO_DIR.mkdir(parents=True, exist_ok=True)
    name = uuid.uuid4().hex + extension
    (PHOTO_DIR / name).write_bytes(data)
    return name


def photo_path(name: str) -> Path | None:
    # Names are generated by save_photo; reject anything else (e.g. "../x").
    if not name or Path(name).name != name or Path(name).suffix not in MEDIA_TYPES:
        return None
    path = PHOTO_DIR / name
    return path if path.is_file() else None


def delete_photo(name: str | None) -> None:
    path = photo_path(name) if name else None
    if path:
        path.unlink(missing_ok=True)
